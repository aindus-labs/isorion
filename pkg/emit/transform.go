package emit

import (
	"fmt"
	"sort"

	"github.com/isorion-lang/isorion/pkg/lang"
)

// annotateTransformer prefixes every emitted file with a deterministic
// "generated" header — the reference Transformer for composite targets
// (`-t kubernetes+annotate`).
type annotateTransformer struct{}

func init() { RegisterTransformer(annotateTransformer{}) }

func (annotateTransformer) Name() string { return "annotate" }

func (annotateTransformer) Apply(target string, files []File) ([]File, error) {
	out := make([]File, len(files))
	header := fmt.Sprintf("# generated by isorion (target: %s) — do not edit\n", target)
	for i, f := range files {
		out[i] = File{Path: f.Path, Content: append([]byte(header), f.Content...)}
	}
	return out, nil
}

// secretName computes the deterministic name of the emitted secret object
// (used by kubernetes/docker-compose conventions).
func secretObjectName(project string) string {
	if project != "" {
		return project + "-secrets"
	}
	return "isorion-secrets"
}

// sortedSecretNames returns doc.Secrets keys in deterministic order.
func sortedSecretNames(secrets map[string]string) []string {
	names := make([]string, 0, len(secrets))
	for n := range secrets {
		names = append(names, n)
	}
	sort.Strings(names)
	return names
}

// splitSecretEnv splits environment values into plain entries and secret refs.
func splitSecretEnv(env map[string]string) (plain map[string]string, secret map[string]string) {
	plain = map[string]string{}
	secret = map[string]string{}
	for k, v := range env {
		if name, ok := lang.SecretName(v); ok {
			secret[k] = name
		} else {
			plain[k] = v
		}
	}
	return plain, secret
}
