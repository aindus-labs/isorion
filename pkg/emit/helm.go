package emit

import (
	"fmt"
	"strings"

	"github.com/isorion-lang/isorion/pkg/lang"
	"github.com/isorion-lang/isorion/pkg/model"
	"gopkg.in/yaml.v3"
)

// helmEmitter emits a minimal Helm chart: Chart.yaml, values.yaml
// (carrying the whole normalized model) and generic templates that
// iterate .Values.services — one Deployment per service, one Service
// per service exposing ports, one Secret when secrets are declared.
type helmEmitter struct{}

func init() { Register(helmEmitter{}) }

func (helmEmitter) Name() string { return "helm" }
func (helmEmitter) Description() string {
	return "Helm chart (Chart.yaml + values.yaml + generic templates)"
}

// chartName derives a DNS-safe chart name.
func chartName(infra *model.Infra) string {
	if infra.ProjectName != "" {
		return strings.ToLower(infra.ProjectName)
	}
	return "isorion-app"
}

func (helmEmitter) Emit(doc *lang.Document, infra *model.Infra) ([]File, error) {
	if len(infra.Services) == 0 {
		return nil, fmt.Errorf("helm target requires at least one service")
	}
	name := chartName(infra)

	chart := map[string]any{
		"apiVersion": "v2",
		"name":       name,
		"description": firstNonEmpty(infra.Description,
			"Helm chart generated by isorion"),
		"type":    "application",
		"version": "0.1.0",
	}
	chartYAML, err := yaml.Marshal(chart)
	if err != nil {
		return nil, err
	}

	// values.yaml — the full normalized model, secret values replaced by
	// "" (they are filled at install time via --set or an external values
	// file; the ENC ciphertext stays out of the chart).
	services := map[string]any{}
	for _, n := range infra.ServiceNames {
		s := infra.Services[n]
		svc := map[string]any{}
		if s.Image != "" {
			svc["image"] = s.Image
		}
		if len(s.Command) > 0 {
			svc["command"] = s.Command
		}
		if s.Replicas != 1 {
			svc["replicas"] = s.Replicas
		}
		if len(s.Ports) > 0 {
			var ports []any
			for _, p := range s.Ports {
				port := map[string]any{"container": p.Container}
				if p.Host != 0 {
					port["host"] = p.Host
				}
				if p.Protocol != "" && p.Protocol != "tcp" {
					port["protocol"] = strings.ToUpper(p.Protocol)
				}
				ports = append(ports, port)
			}
			svc["ports"] = ports
		}
		plain, secret := splitSecretEnv(s.Environment)
		if len(plain)+len(secret) > 0 {
			env := map[string]any{}
			for _, k := range sortedEnvKeys(plain) {
				env[k] = plain[k]
			}
			for _, k := range sortedEnvKeys(secret) {
				env[k] = map[string]any{"secretKeyRef": map[string]any{
					"name": name + "-secrets", "key": secret[k],
				}}
			}
			svc["env"] = env
		}
		if len(s.Labels) > 0 {
			svc["labels"] = s.Labels
		}
		for k, v := range s.Extra {
			svc[k] = v
		}
		services[n] = svc
	}
	values := map[string]any{"services": services}
	if len(doc.Secrets) > 0 {
		decl := map[string]any{}
		for _, n := range sortedSecretNames(doc.Secrets) {
			decl[n] = "" // filled at install time
		}
		values["secrets"] = decl
	}
	valuesYAML, err := yaml.Marshal(values)
	if err != nil {
		return nil, err
	}

	return []File{
		{Path: name + "/Chart.yaml", Content: chartYAML},
		{Path: name + "/values.yaml", Content: valuesYAML},
		{Path: name + "/templates/deployment.yaml", Content: []byte(helmDeploymentTpl)},
		{Path: name + "/templates/service.yaml", Content: []byte(helmServiceTpl)},
		{Path: name + "/templates/secret.yaml", Content: []byte(helmSecretTpl)},
	}, nil
}

// Warn reports model fields silently dropped by the Helm chart.
func (helmEmitter) Warn(_ *lang.Document, infra *model.Infra) []string {
	var out []string
	for _, name := range infra.ServiceNames {
		s := infra.Services[name]
		if s.Build != "" {
			out = append(out, fmt.Sprintf("services.%s.build ignored by target helm (charts deploy pre-built images)", name))
		}
		if len(s.DependsOn) > 0 {
			out = append(out, fmt.Sprintf("services.%s.depends_on ignored by target helm (k8s is not ordered — use initContainers in Extra)", name))
		}
		if s.Restart != "" {
			out = append(out, fmt.Sprintf("services.%s.restart ignored by target helm (restartPolicy is always Always)", name))
		}
		if len(s.Volumes) > 0 {
			out = append(out, fmt.Sprintf("services.%s.volumes ignored by target helm (declare them in Extra → templates)", name))
		}
		if len(s.Networks) > 0 {
			out = append(out, fmt.Sprintf("services.%s.networks ignored by target helm", name))
		}
	}
	return out
}

// helmDeploymentTpl iterates .Values.services → one Deployment each.
const helmDeploymentTpl = `{{- range $name, $svc := .Values.services }}
apiVersion: apps/v1
kind: Deployment
metadata:
  name: {{ $name }}
  labels:
    app.kubernetes.io/name: {{ $name }}
    app.kubernetes.io/managed-by: isorion-helm
spec:
  replicas: {{ $svc.replicas | default 1 }}
  selector:
    matchLabels:
      app.kubernetes.io/name: {{ $name }}
  template:
    metadata:
      labels:
        app.kubernetes.io/name: {{ $name }}
    spec:
      containers:
        - name: {{ $name }}
          image: {{ $svc.image | quote }}
          {{- with $svc.command }}
          command: {{ toJson . }}
          {{- end }}
          {{- with $svc.ports }}
          ports:
            {{- range . }}
            - containerPort: {{ .container }}
              {{- if .protocol }}
              protocol: {{ .protocol }}
              {{- end }}
            {{- end }}
          {{- end }}
          {{- with $svc.env }}
          env:
            {{- range $k, $v := . }}
            - name: {{ $k }}
              {{- if kindIs "map" $v }}
              valueFrom:
                secretKeyRef:
                  name: {{ $v.secretKeyRef.name }}
                  key: {{ $v.secretKeyRef.key }}
              {{- else }}
              value: {{ $v | quote }}
              {{- end }}
            {{- end }}
          {{- end }}
---
{{- end }}
`

// helmServiceTpl iterates services with ports → one ClusterIP Service each.
const helmServiceTpl = `{{- range $name, $svc := .Values.services }}
{{- if $svc.ports }}
apiVersion: v1
kind: Service
metadata:
  name: {{ $name }}
  labels:
    app.kubernetes.io/name: {{ $name }}
    app.kubernetes.io/managed-by: isorion-helm
spec:
  type: ClusterIP
  selector:
    app.kubernetes.io/name: {{ $name }}
  ports:
    {{- range $svc.ports }}
    - port: {{ .host | default .container }}
      targetPort: {{ .container }}
      {{- if .protocol }}
      protocol: {{ .protocol }}
      {{- end }}
    {{- end }}
---
{{- end }}
{{- end }}
`

// helmSecretTpl emits one Secret holding install-time values.
const helmSecretTpl = `{{- if .Values.secrets }}
apiVersion: v1
kind: Secret
metadata:
  name: {{ .Chart.Name }}-secrets
  labels:
    app.kubernetes.io/managed-by: isorion-helm
type: Opaque
stringData:
  {{- range $k, $v := .Values.secrets }}
  {{ $k }}: {{ $v | quote }}
  {{- end }}
{{- end }}
`

func firstNonEmpty(vals ...string) string {
	for _, v := range vals {
		if v != "" {
			return v
		}
	}
	return ""
}
