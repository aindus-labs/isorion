func TestWarnings(t *testing.T) {
	doc, infra := loadFixture(t)
	// fixture: api has depends_on → kubernetes must warn
	_, warns, err := Run("kubernetes", doc, infra)
	if err != nil {
		t.Fatal(err)
	}
	found := false
	for _, w := range warns {
		if strings.Contains(w, "depends_on") {
			found = true
		}
	}
	if !found {
		t.Fatalf("expected depends_on warning, got %v", warns)
	}
	// docker-compose passes everything through → no warnings
	_, warns, err = Run("docker-compose", doc, infra)
	if err != nil {
		t.Fatal(err)
	}
	if len(warns) != 0 {
		t.Fatalf("unexpected compose warnings: %v", warns)
	}
}

func TestSecretsEmission(t *testing.T) {
	src := []byte(`version: "1.0"
project:
  name: webapp
secrets:
  db_password: "ENC[age:xyz]"
services:
  api:
    image: nginx
    environment:
      PASS: ${secret("db_password")}
`)
	doc, err := lang.Load("t.isor", src)
	if err != nil {
		t.Fatal(err)
	}
	infra, err := model.FromBody(doc.Version, doc.Body)
	if err != nil {
		t.Fatal(err)
	}

	// kubernetes: secretKeyRef + Secret manifest with ENC blob
	files := emitTarget(t, "kubernetes", doc, infra)
	var dep, secret string
	for _, f := range files {
		if strings.HasSuffix(f.Path, "api-deployment.yaml") {
			dep = string(f.Content)
		}
		if strings.HasSuffix(f.Path, "-secret.yaml") {
			secret = string(f.Content)
		}
	}
	if !strings.Contains(dep, "secretKeyRef") || strings.Contains(dep, "ENC[") {
		t.Fatalf("deployment must reference, not contain, the secret:\n%s", dep)
	}
	if !strings.Contains(secret, "kind: Secret") || !strings.Contains(secret, "ENC[age:xyz]") {
		t.Fatalf("secret manifest:\n%s", secret)
	}

	// docker-compose: env placeholder + external secret
	files = emitTarget(t, "docker-compose", doc, infra)
	got := string(files[0].Content)
	if !strings.Contains(got, "${SECRET_db_password}") || !strings.Contains(got, "external: true") {
		t.Fatalf("compose secrets:\n%s", got)
	}
}

func TestModelServiceNames(t *testing.T) {
	_, infra := loadFixture(t)
	if len(infra.ServiceNames) != 2 || infra.ServiceNames[0] != "api" || infra.ServiceNames[1] != "db" {
		t.Fatalf("service names = %v", infra.ServiceNames)
	}
	api := infra.Services["api"]
	if api.Replicas != 5 {
		t.Fatalf("replicas = %d", api.Replicas)
	}
	if len(api.Ports) != 1 || api.Ports[0].Container != 8080 || api.Ports[0].Host != 80 {
		t.Fatalf("ports = %+v", api.Ports)
	}
}
