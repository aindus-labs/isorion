const fixture = `
version: "1.0"

variables:
  env: "production"

project:
  name: webapp

services:
  api:
    image: "nginx:1.25"
    @if $env == "production":
      replicas: 5
    @else:
      replicas: 1
    ports:
      - "80:8080"
    environment:
      APP_ENV: $env
    depends_on:
      - db

  db:
    image: "postgres:16"

networks:
  front: {}
`

func loadFixture(t *testing.T) (*lang.Document, *model.Infra) {
	t.Helper()
	doc, err := lang.Load("fixture.isor", []byte(fixture))
	if err != nil {
		t.Fatal(err)
	}
	infra, err := model.FromBody(doc.Version, doc.Body)
	if err != nil {
		t.Fatal(err)
	}
	return doc, infra
}

func emitTarget(t *testing.T, name string, doc *lang.Document, infra *model.Infra) []File {
	t.Helper()
	e, err := Get(name)
	if err != nil {
		t.Fatal(err)
	}
	files, err := e.Emit(doc, infra)
	if err != nil {
		t.Fatalf("emit %s: %v", name, err)
	}
	if len(files) == 0 {
		t.Fatalf("emit %s: no files", name)
	}
	return files
}

func TestAllTargets(t *testing.T) {
	doc, infra := loadFixture(t)
	for _, name := range Names() {
		files := emitTarget(t, name, doc, infra)
		total := 0
		for _, f := range files {
			total += len(f.Content)
		}
		if total == 0 {
			t.Errorf("target %s emitted empty content", name)
		}
	}
}

