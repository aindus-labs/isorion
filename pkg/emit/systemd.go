package emit

import (
	"fmt"
	"strings"

	"github.com/isorion-lang/isorion/pkg/lang"
	"github.com/isorion-lang/isorion/pkg/model"
)

// systemdEmitter emits one <project>-<svc>.service unit per service.
// Units run containers via `docker run` (podman-compatible if the user
// points the container runtime elsewhere) — matching ORION's native
// adapter: a service IS a container lifecycle managed by systemd.
// depends_on maps to After=/Requires= on sibling units.
type systemdEmitter struct{}

func init() { Register(systemdEmitter{}) }

func (systemdEmitter) Name() string        { return "systemd" }
func (systemdEmitter) Description() string { return "systemd units (one .service per service)" }

func (systemdEmitter) Emit(doc *lang.Document, infra *model.Infra) ([]File, error) {
	if len(infra.Services) == 0 {
		return nil, fmt.Errorf("systemd target requires at least one service")
	}
	prefix := infra.ProjectName
	if prefix == "" {
		prefix = "isorion"
	}

	secretFile := "/etc/isorion/" + prefix + "-secrets.env"
	var files []File
	for _, name := range infra.ServiceNames {
		s := infra.Services[name]
		unit := prefix + "-" + name + ".service"
		var b strings.Builder

		b.WriteString("[Unit]\n")
		fmt.Fprintf(&b, "Description=isorion service %s (%s)\n", name, firstNonEmpty(s.Image, s.Build))
		b.WriteString("After=network-online.target docker.service\n")
		b.WriteString("Wants=network-online.target\n")
		b.WriteString("Requires=docker.service\n")
		for _, dep := range s.DependsOn {
			fmt.Fprintf(&b, "After=%s-%s.service\nRequires=%s-%s.service\n", prefix, dep, prefix, dep)
		}

		b.WriteString("\n[Service]\n")
		b.WriteString("Type=simple\n")
		restart := s.Restart
		if restart == "" || restart == "unless-stopped" {
			restart = "always"
		}
		if restart == "no" {
			restart = "no"
		}
		fmt.Fprintf(&b, "Restart=%s\n", restart)
		fmt.Fprintf(&b, "RestartSec=2\n")

		plain, secret := splitSecretEnv(s.Environment)
		for _, k := range sortedEnvKeys(plain) {
			fmt.Fprintf(&b, "Environment=%s=%s\n", k, systemdQuote(plain[k]))
		}
		if len(secret) > 0 || len(doc.Secrets) > 0 {
			// Secrets never land in the unit — loaded from a root-owned
			// env file (0600) at start time.
			fmt.Fprintf(&b, "EnvironmentFile=-%s\n", secretFile)
		}

		fmt.Fprintf(&b, "ExecStartPre=-/usr/bin/docker rm -f %s\n", unitName(prefix, name))
		var run strings.Builder
		fmt.Fprintf(&run, "/usr/bin/docker run --rm --name %s", unitName(prefix, name))
		for _, p := range s.Ports {
			fmt.Fprintf(&run, " -p %s", p.Compose())
		}
		for _, v := range s.Volumes {
			fmt.Fprintf(&run, " -v %s", v)
		}
		for _, n := range s.Networks {
			fmt.Fprintf(&run, " --network %s", n)
		}
		for _, k := range sortedEnvKeys(plain) {
			fmt.Fprintf(&run, " -e %s", k)
		}
		for _, k := range sortedEnvKeys(secret) {
			fmt.Fprintf(&run, " -e %s", k)
		}
		if s.Image != "" {
			fmt.Fprintf(&run, " %s", s.Image)
		}
		for _, c := range s.Command {
			fmt.Fprintf(&run, " %s", c)
		}
		fmt.Fprintf(&b, "ExecStart=%s\n", run.String())
		fmt.Fprintf(&b, "ExecStop=/usr/bin/docker stop %s\n", unitName(prefix, name))

		b.WriteString("\n[Install]\nWantedBy=multi-user.target\n")
		files = append(files, File{Path: unit, Content: []byte(b.String())})
	}

	if len(doc.Secrets) > 0 {
		var env strings.Builder
		env.WriteString("# generated by isorion — install at " + secretFile + " (chmod 0600, root:root)\n")
		for _, n := range sortedSecretNames(doc.Secrets) {
			fmt.Fprintf(&env, "%s=%s\n", n, doc.Secrets[n])
		}
		files = append(files, File{Path: prefix + "-secrets.env.example", Content: []byte(env.String())})
	}
	return files, nil
}

// Warn reports model fields silently dropped by the systemd target.
func (systemdEmitter) Warn(_ *lang.Document, infra *model.Infra) []string {
	var out []string
	for _, name := range infra.ServiceNames {
		s := infra.Services[name]
		for _, k := range sortedAnyKeys(s.Extra) {
			out = append(out, fmt.Sprintf("services.%s.%s ignored by target systemd", name, k))
		}
		if s.Build != "" {
			out = append(out, fmt.Sprintf("services.%s.build ignored by target systemd (units run images — build first with docker build)", name))
		}
		if s.Replicas != 1 {
			out = append(out, fmt.Sprintf("services.%s.replicas=%d ignored by target systemd (one unit = one container — instantiate %s@.service manually)", name, s.Replicas, name))
		}
		if len(s.Labels) > 0 {
			out = append(out, fmt.Sprintf("services.%s.labels ignored by target systemd", name))
		}
	}
	return out
}

// unitName is the docker container name (no .service suffix).
func unitName(prefix, name string) string { return prefix + "-" + name }

// systemdQuote wraps a value in double quotes when it contains characters
// systemd would split on (spaces, %, $).
func systemdQuote(v string) string {
	if strings.ContainsAny(v, " %$\t\"") {
		return `"` + strings.ReplaceAll(v, `"`, `\"`) + `"`
	}
	return v
}
