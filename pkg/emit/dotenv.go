package emit

import (
	"fmt"
	"strings"

	"github.com/isorion-lang/isorion/pkg/lang"
	"github.com/isorion-lang/isorion/pkg/model"
)

// dotenvEmitter extracts the flat environment into a .env file:
// SERVICE_KEY=value lines in service order, secret refs rendered as
// ${SECRET_name} placeholders (plaintext never lands in the artifact).
type dotenvEmitter struct{}

func init() { Register(dotenvEmitter{}) }

func (dotenvEmitter) Name() string { return "dotenv" }
func (dotenvEmitter) Description() string {
	return "Flattened .env file (SERVICE_KEY=value, secrets as ${SECRET_*} refs)"
}

func (dotenvEmitter) Emit(doc *lang.Document, infra *model.Infra) ([]File, error) {
	var b strings.Builder
	b.WriteString("# generated by isorion — secret values must be provided at run time\n")
	for _, name := range infra.ServiceNames {
		s := infra.Services[name]
		if len(s.Environment) == 0 {
			continue
		}
		prefix := envKey(name)
		fmt.Fprintf(&b, "\n# service %s\n", name)
		for _, k := range sortedEnvKeys(s.Environment) {
			v := s.Environment[k]
			if sn, ok := lang.SecretName(v); ok {
				v = "${SECRET_" + sn + "}"
			}
			fmt.Fprintf(&b, "%s_%s=%s\n", prefix, envKey(k), v)
		}
	}
	return []File{{Path: ".env", Content: []byte(b.String())}}, nil
}

// envKey normalizes a name into ENV_VAR casing: "api-v2" → "API_V2".
func envKey(s string) string {
	var b strings.Builder
	for _, c := range s {
		switch {
		case c >= 'a' && c <= 'z':
			b.WriteRune(c - 'a' + 'A')
		case c == '-' || c == '.':
			b.WriteByte('_')
		default:
			b.WriteRune(c)
		}
	}
	return b.String()
}
